import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {areaGrid} from '../../../web/src/lib/areaGrid.js';
const read=name=>JSON.parse(readFileSync(new URL(name,import.meta.url),'utf8'));
const baseline=read('baseline.json'),after=read('browser-after-reopen.json');
assert.deepEqual(after,baseline,'Complete live browser baseline survives generic save/Undo and native archive reopen');
assert.deepEqual(read('browser-final.json'),baseline,'Final build preserves the complete live browser baseline');
const edited=read('browser-explicit-edit.json');
const original=baseline.shapes.find(s=>s.planting_grid),converted=edited.shapes.find(s=>s.id===original.id);
assert.ok(converted.area_grid);assert.equal(converted.planting_grid,undefined);
assert.equal(areaGrid(converted,{widthPx:5184,heightPx:3456,upp:baseline.sheets[0].units_per_px}).count,110);
delete converted.area_grid;converted.planting_grid=original.planting_grid;assert.deepEqual(edited,baseline);
const mcp=read('public-restored.json');assert.deepEqual(mcp.shapes,baseline.shapes);
const demo=read('demo-takeoff.json'),saved=read('demo-browser-after.json'),before=read('demo-before.json');
for(const key of ['shapes','conditions','sheets'])assert.deepEqual(saved[key],demo[key]);
assert.equal(areaGrid(saved.shapes[0],{widthPx:6048,heightPx:4320,upp:1/18}).count,8);
assert.equal(saved.shapes[0].computed.area_sf,128);
assert.equal(saved.shapes[0].area_grid.source_callout_id,undefined);
const stripped=structuredClone(saved.shapes);delete stripped[0].area_grid;assert.deepEqual(stripped,before.shapes);
console.log('PASS: public project exactly unchanged; generic edit only replaces grid metadata; bundled grid retains 128 SF, eight positions, original ID/review and no printed source through archive reopen.');
